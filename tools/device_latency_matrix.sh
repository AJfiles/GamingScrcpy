#!/usr/bin/env bash
# §C: measure the host-side latency of the real mirror instead of assuming it.
#
# The full cross product of the requested dimensions is 3 buffers x 2 codecs x
# 3 renderers x 2 low-latency x 4 encoder presets = 144 sessions, which at ~15 s
# each is 36 minutes of someone's tablet tied up. So this sweeps it one factor at
# a time from a fixed reference point, in three stages, plus a repeat of the
# reference probe: the repeat is what makes the table readable, because it shows
# how much of any difference between two rows is just machine noise.
#
#   stage A  --video-buffer (0 / 50 / default) x --video-codec (h264 / h265)
#   stage B  --render-driver (direct3d11 / vulkan / opengl) x --game-low-latency
#   stage C  encoder preset (default / ultrafast / fast / medium)
#
# Every number comes from the fork's own telemetry-summary (median/p90/p99 of
# per-frame receive -> present), never from the frame rate. What is NOT included
# is the device's own capture+encode time, which is not observable from the host,
# so this is the host half of glass-to-glass.
#
# Needs a device; without one it prints SKIP and exits 0.
#
#   bash tools/device_latency_matrix.sh [seconds-per-probe] [stage]
set -u

here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/.." && pwd)
client="$root/dist/GamingScrcpy/scrcpy/scrcpy.exe"
adbwin="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/dist/GamingScrcpy/scrcpy/adb.exe"
SECS="${1:-14}"
STAGE="${2:-all}"

audit() { bash "$here/adb_audit.sh" "$*"; }

[ -f "$client" ] || { echo "SKIP matrix (no packaged client)"; exit 0; }
audit "adb devices"
serial=$(cd "$root/dist/GamingScrcpy/scrcpy" && ./adb.exe devices 2>/dev/null \
        | awk 'NR>1 && $2=="device" {print $1; exit}')
if [ -z "$serial" ]; then
    echo "SKIP matrix (no adb device attached)"
    exit 0
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
fail=0
n=0

# reference point for the one-factor-at-a-time sweep
REF_BUFFER=0
REF_CODEC=h264
REF_RENDERER=direct3d11
REF_LOWLAT=1
REF_PRESET=ultrafast

probe() { # probe <stage> <label> <args...>
    local stage=$1 label=$2; shift 2
    local log="$tmp/${stage}-${n}.log"
    n=$((n + 1))
    audit "scrcpy --serial=$serial --game-telemetry-log --video-bit-rate=48M --max-fps=60 --time-limit=$SECS $*"
    ADB="$adbwin" "$client" --serial="$serial" --game-telemetry-log \
        --video-bit-rate=48M --max-fps=60 --time-limit="$SECS" "$@" \
        > "$log.raw" 2>&1 &
    local pid=$!
    sleep 5
    powershell.exe -NoProfile -ExecutionPolicy Bypass \
        -File "$here/wake_device_screen.ps1" > "$log.wake" 2>&1
    wait "$pid"
    sed 's/\x1b\[[0-9;]*m//g' "$log.raw" > "$log"

    local sum kb fps src scene
    sum=$(grep -o 'telemetry-summary:.*' "$log" | tail -1)
    kb=$(grep -o 'v_kbps=[0-9]*' "$log" | cut -d= -f2 | sort -n \
         | awk '{a[NR]=$1} END {if (NR) print a[int((NR+1)/2)]; else print 0}')
    fps=$(grep -o 'fps=[0-9.]*' "$log" | cut -d= -f2 | sort -n \
          | awk '{a[NR]=$1} END {if (NR) print a[int((NR+1)/2)]; else print "na"}')
    src=$(grep -o 'src=[0-9]*x[0-9]*' "$log" | tail -1 | cut -d= -f2)
    # a dark or idle screen makes the encoder emit near-empty frames, and the
    # latency then describes nothing a player would see
    scene=live
    [ "${kb:-0}" -lt 200 ] && scene=static
    if [ -z "$sum" ]; then
        echo "FAIL ${stage} ${label}: no telemetry summary"
        tail -4 "$log"
        fail=1
        return
    fi
    echo "| ${stage} | ${label} | $(echo "$sum" | sed -E 's/telemetry-summary: //; s/lat_//g') | fps=${fps} | ${scene} | ${src} |"
    echo "| ${stage} | ${label} | $(echo "$sum" | sed -E 's/telemetry-summary: //; s/lat_//g') | fps=${fps} | ${scene} | ${src} |" \
        >> "$root/out/dev/latency_matrix.md"
}

args_for() { # args_for <buffer> <codec> <renderer> <lowlat 0|1> <preset>
    local buffer=$1 codec=$2 renderer=$3 lowlat=$4 preset=$5
    local -a a=()
    [ "$buffer" = default ] || a+=("--video-buffer=$buffer")
    a+=("--video-codec=$codec")
    a+=("--render-driver=$renderer")
    [ "$lowlat" = 1 ] && a+=("--game-low-latency")
    case "$preset" in
        ultrafast) a+=("--video-codec-options=latency:int=9");;
        fast)      a+=("--video-codec-options=latency:int=7");;
        medium)    a+=("--video-codec-options=latency:int=5");;
        *) ;;
    esac
    printf '%s ' "${a[@]}"
}

mkdir -p "$root/out/dev"
# a full sweep starts a new table; a single stage appends to the existing one
[ "$STAGE" = all ] && : > "$root/out/dev/latency_matrix.md"
{
    echo ""
    echo "<!-- generated by tools/device_latency_matrix.sh on $(date -u +%FT%TZ)," \
         "probe=${SECS}s, serial=$serial -->"
    echo ""
    echo "| stage | combination | med / p90 / p99 / max / avg (ms) | fps | scene | src |"
    echo "|-------|-------------|-----------------------------------|-----|-------|-----|"
} >> "$root/out/dev/latency_matrix.md"

if [ "$STAGE" = all ] || [ "$STAGE" = A ]; then
    for buffer in 0 50 default; do
        for codec in h264 h265; do
            probe A "buffer=$buffer codec=$codec" $(args_for "$buffer" "$codec" \
                    "$REF_RENDERER" "$REF_LOWLAT" "$REF_PRESET")
        done
    done
fi

if [ "$STAGE" = all ] || [ "$STAGE" = B ]; then
    for renderer in direct3d11 vulkan opengl; do
        for lowlat in 1 0; do
            probe B "renderer=$renderer lowlat=$lowlat" $(args_for \
                    "$REF_BUFFER" "$REF_CODEC" "$renderer" "$lowlat" "$REF_PRESET")
        done
    done
fi

if [ "$STAGE" = all ] || [ "$STAGE" = C ]; then
    for preset in default ultrafast fast medium; do
        probe C "preset=$preset" $(args_for "$REF_BUFFER" "$REF_CODEC" \
                "$REF_RENDERER" "$REF_LOWLAT" "$preset")
    done
    # the control: the reference configuration again, so the spread between this
    # and the identical earlier row is the noise floor of the whole table
    probe R "repeat of reference" $(args_for "$REF_BUFFER" "$REF_CODEC" \
            "$REF_RENDERER" "$REF_LOWLAT" "$REF_PRESET")
fi

echo "RESULT matrix probes=$n serial=$serial seconds_per_probe=$SECS"
echo "RESULT matrix device size seen: native, no --max-size and no --crop is used by this harness"
if [ $fail -eq 0 ] && [ "$n" -gt 0 ]; then
    echo "MATRIX OK"
    exit 0
fi
[ "$n" -gt 0 ] || exit 0
echo "MATRIX FAILED"
exit 1
